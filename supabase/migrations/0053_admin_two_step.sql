-- 0053: two-step sign-in for the owner portal (Phase 5).
--
-- is_admin() now needs BOTH the admin role (public.user_roles) AND a second
-- factor checked within the last 12 hours, for the session that is calling:
--   * an authenticator app (Supabase TOTP MFA: the JWT is aal2 and its `amr`
--     claim carries a recent "totp" entry), or
--   * a one-time code sent by WhatsApp (SMS fallback), recorded below in
--     public.admin_step_up against the JWT's session_id.
-- Every admin RLS policy and the DAL call is_admin(), so a password-only admin
-- session has no admin rights anywhere, including direct API calls.
--
-- One-time codes are generated by the app (CSPRNG), sent, and stored here only
-- as a keyed hash (HMAC-SHA256 with a server-side pepper the database never
-- sees). Codes live 10 minutes, are single-use and bound to one session and one
-- purpose; 5 wrong tries lock the code, and resending keeps the failure count.
-- All functions except admin_two_step_status() are service_role only.

-- ---------------------------------------------------------------------------
-- A) Tables
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.admin_otp_phones (
  user_id     uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  phone_e164  text NOT NULL CHECK (phone_e164 ~ '^\+91[6-9][0-9]{9}$'),
  verified_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.otp_challenges (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id      uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  session_id   uuid NOT NULL,
  purpose      text NOT NULL CHECK (purpose IN ('admin_sign_in', 'phone_enrol')),
  phone_e164   text NOT NULL CHECK (phone_e164 ~ '^\+91[6-9][0-9]{9}$'),
  code_hash    text NOT NULL CHECK (code_hash ~ '^[0-9a-f]{64}$'),
  attempts     smallint NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
  sends        smallint NOT NULL DEFAULT 1 CHECK (sends BETWEEN 1 AND 5),
  created_at   timestamptz NOT NULL DEFAULT now(),
  last_sent_at timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL,
  consumed_at  timestamptz,
  locked_at    timestamptz
);
-- At most one open code per session and purpose.
CREATE UNIQUE INDEX IF NOT EXISTS otp_challenges_open_uq
  ON public.otp_challenges (session_id, purpose)
  WHERE consumed_at IS NULL AND locked_at IS NULL;
CREATE INDEX IF NOT EXISTS otp_challenges_user_created_idx
  ON public.otp_challenges (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.otp_deliveries (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  challenge_id        uuid NOT NULL REFERENCES public.otp_challenges(id) ON DELETE CASCADE,
  channel             text NOT NULL CHECK (channel IN ('whatsapp', 'sms')),
  provider_message_id text UNIQUE,
  status              text NOT NULL CHECK (status IN ('sent', 'delivered', 'read', 'failed')),
  error               text CHECK (char_length(error) <= 200),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS otp_deliveries_challenge_idx ON public.otp_deliveries (challenge_id);

CREATE TABLE IF NOT EXISTS public.admin_step_up (
  session_id  uuid PRIMARY KEY,
  user_id     uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  method      text NOT NULL CHECK (method IN ('whatsapp', 'sms')),
  verified_at timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS admin_step_up_user_idx ON public.admin_step_up (user_id);

ALTER TABLE public.admin_otp_phones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.otp_challenges   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.otp_deliveries   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_step_up    ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_otp_phones, public.otp_challenges, public.otp_deliveries, public.admin_step_up
  FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE
  ON public.admin_otp_phones, public.otp_challenges, public.otp_deliveries, public.admin_step_up
  TO service_role;
-- No policies for anon/authenticated: RLS on + no grants = no access at all.

-- ---------------------------------------------------------------------------
-- B) Second-factor check for the calling session
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.has_recent_second_factor()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT
    -- Authenticator app: aal2 with a TOTP (or other MFA) entry from the last 12 h.
    (
      COALESCE((SELECT auth.jwt()) ->> 'aal', '') = 'aal2'
      AND EXISTS (
        SELECT 1
          FROM jsonb_array_elements(
                 CASE WHEN jsonb_typeof((SELECT auth.jwt()) -> 'amr') = 'array'
                      THEN (SELECT auth.jwt()) -> 'amr' ELSE '[]'::jsonb END) a
         WHERE a ->> 'method' IN ('totp', 'mfa/totp', 'mfa/phone', 'mfa/webauthn')
           AND (a ->> 'timestamp') ~ '^[0-9]{1,12}$'
           AND to_timestamp((a ->> 'timestamp')::bigint) > now() - interval '12 hours'
      )
    )
    OR
    -- WhatsApp / SMS code verified for this very session.
    EXISTS (
      SELECT 1
        FROM public.admin_step_up s
       WHERE s.user_id = (SELECT auth.uid())
         AND s.session_id::text = COALESCE((SELECT auth.jwt()) ->> 'session_id', '')
         AND s.expires_at > now()
    );
$$;
REVOKE ALL ON FUNCTION public.has_recent_second_factor() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.has_recent_second_factor() TO anon, authenticated, service_role;

-- is_admin(): role AND recent second factor. Signature unchanged, so every
-- existing policy and the DAL pick this up.
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
           SELECT 1 FROM public.user_roles ur
            WHERE ur.user_id = (SELECT auth.uid())
              AND ur.role = 'admin'::public.user_role
         )
     AND public.has_recent_second_factor();
$$;
REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_admin() TO anon, authenticated, service_role;

-- What the sign-in pages need to know about the caller, and nothing else.
CREATE OR REPLACE FUNCTION public.admin_two_step_status()
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT jsonb_build_object(
    'admin_role', EXISTS (
       SELECT 1 FROM public.user_roles ur
        WHERE ur.user_id = (SELECT auth.uid()) AND ur.role = 'admin'::public.user_role),
    'second_factor', public.has_recent_second_factor(),
    'phone_last4', (SELECT right(p.phone_e164, 4) FROM public.admin_otp_phones p
                     WHERE p.user_id = (SELECT auth.uid()))
  );
$$;
REVOKE ALL ON FUNCTION public.admin_two_step_status() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_two_step_status() TO authenticated, service_role;

-- ---------------------------------------------------------------------------
-- C) Issue / resend a code
-- ---------------------------------------------------------------------------
-- Errors: NOT_ADMIN, PHONE_NOT_ENROLLED, OTP_RATE_LIMITED, OTP_LOCKED,
--         OTP_TOO_MANY_SENDS, OTP_RESEND_TOO_SOON, INVALID_PHONE, INVALID_PURPOSE.
CREATE OR REPLACE FUNCTION public.otp_issue(
  p_user_id    uuid,
  p_session_id uuid,
  p_purpose    text,
  p_phone      text,
  p_code_hash  text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_open   public.otp_challenges%ROWTYPE;
  v_phone  text;
  v_recent int;
BEGIN
  IF p_purpose NOT IN ('admin_sign_in', 'phone_enrol') THEN
    RAISE EXCEPTION 'INVALID_PURPOSE';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.user_roles
                  WHERE user_id = p_user_id AND role = 'admin'::public.user_role) THEN
    RAISE EXCEPTION 'NOT_ADMIN';
  END IF;

  -- Serialise per user so parallel sends cannot slip past the limits.
  PERFORM pg_advisory_xact_lock(hashtextextended('otp:' || p_user_id::text, 0));

  IF p_purpose = 'admin_sign_in' THEN
    SELECT phone_e164 INTO v_phone FROM public.admin_otp_phones WHERE user_id = p_user_id;
    IF v_phone IS NULL THEN
      RAISE EXCEPTION 'PHONE_NOT_ENROLLED';
    END IF;
  ELSE
    v_phone := p_phone;
    IF v_phone IS NULL OR v_phone !~ '^\+91[6-9][0-9]{9}$' THEN
      RAISE EXCEPTION 'INVALID_PHONE';
    END IF;
  END IF;

  -- Housekeeping: old codes and old step-ups.
  DELETE FROM public.otp_challenges WHERE created_at < now() - interval '2 days';
  DELETE FROM public.admin_step_up  WHERE expires_at < now() - interval '1 day';

  SELECT * INTO v_open
    FROM public.otp_challenges
   WHERE session_id = p_session_id AND purpose = p_purpose
     AND consumed_at IS NULL AND locked_at IS NULL
   FOR UPDATE;

  IF FOUND AND v_open.expires_at > now() AND v_open.phone_e164 = v_phone THEN
    -- Resend: new code, same row, failure count kept.
    IF v_open.sends >= 5 THEN
      RAISE EXCEPTION 'OTP_TOO_MANY_SENDS';
    END IF;
    IF v_open.last_sent_at > now() - interval '30 seconds' THEN
      RAISE EXCEPTION 'OTP_RESEND_TOO_SOON';
    END IF;
    UPDATE public.otp_challenges
       SET code_hash = p_code_hash, sends = sends + 1, last_sent_at = now(),
           expires_at = now() + interval '10 minutes'
     WHERE id = v_open.id;
    RETURN jsonb_build_object('challenge_id', v_open.id, 'phone_last4', right(v_phone, 4),
                              'sends', v_open.sends + 1, 'attempts_left', 5 - v_open.attempts);
  END IF;

  IF FOUND THEN
    -- Expired or for another number: close it. The new code counts towards
    -- the hourly limit below, so "let it expire, ask again" gains nothing.
    UPDATE public.otp_challenges SET locked_at = now() WHERE id = v_open.id;
  END IF;

  -- New codes: at most 3 per user per hour, and none while a code locked by
  -- wrong guesses is less than 15 minutes old.
  SELECT count(*) INTO v_recent
    FROM public.otp_challenges
   WHERE user_id = p_user_id AND created_at > now() - interval '1 hour';
  IF v_recent >= 3 THEN
    RAISE EXCEPTION 'OTP_RATE_LIMITED';
  END IF;
  IF EXISTS (SELECT 1 FROM public.otp_challenges
              WHERE user_id = p_user_id AND attempts >= 5
                AND locked_at > now() - interval '15 minutes') THEN
    RAISE EXCEPTION 'OTP_LOCKED';
  END IF;

  INSERT INTO public.otp_challenges (user_id, session_id, purpose, phone_e164, code_hash, expires_at)
  VALUES (p_user_id, p_session_id, p_purpose, v_phone, p_code_hash, now() + interval '10 minutes')
  RETURNING * INTO v_open;

  RETURN jsonb_build_object('challenge_id', v_open.id, 'phone_last4', right(v_phone, 4),
                            'sends', 1, 'attempts_left', 5);
END;
$$;

-- ---------------------------------------------------------------------------
-- D) Check a code
-- ---------------------------------------------------------------------------
-- Never raises for a wrong code (the failed attempt must be committed);
-- returns {ok, reason, attempts_left}. reason: NOT_FOUND, USED, LOCKED,
-- EXPIRED, WRONG_CODE.
CREATE OR REPLACE FUNCTION public.otp_verify(
  p_challenge_id uuid,
  p_user_id      uuid,
  p_session_id   uuid,
  p_code_hash    text
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_c      public.otp_challenges%ROWTYPE;
  v_method text;
BEGIN
  SELECT * INTO v_c FROM public.otp_challenges WHERE id = p_challenge_id FOR UPDATE;
  IF NOT FOUND OR v_c.user_id <> p_user_id OR v_c.session_id <> p_session_id THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'NOT_FOUND', 'attempts_left', 0);
  END IF;
  IF v_c.consumed_at IS NOT NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'USED', 'attempts_left', 0);
  END IF;
  IF v_c.locked_at IS NOT NULL OR v_c.attempts >= 5 THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'LOCKED', 'attempts_left', 0);
  END IF;
  IF v_c.expires_at <= now() THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'EXPIRED', 'attempts_left', 5 - v_c.attempts);
  END IF;

  IF p_code_hash IS NULL OR p_code_hash <> v_c.code_hash THEN
    UPDATE public.otp_challenges
       SET attempts  = attempts + 1,
           locked_at = CASE WHEN attempts + 1 >= 5 THEN now() ELSE NULL END
     WHERE id = v_c.id;
    RETURN jsonb_build_object(
      'ok', false,
      'reason', CASE WHEN v_c.attempts + 1 >= 5 THEN 'LOCKED' ELSE 'WRONG_CODE' END,
      'attempts_left', 5 - (v_c.attempts + 1));
  END IF;

  UPDATE public.otp_challenges SET consumed_at = now() WHERE id = v_c.id;

  IF v_c.purpose = 'admin_sign_in' THEN
    SELECT CASE WHEN bool_or(d.channel = 'sms') AND NOT bool_or(d.channel = 'whatsapp' AND d.status IN ('delivered', 'read'))
                THEN 'sms' ELSE 'whatsapp' END
      INTO v_method
      FROM public.otp_deliveries d WHERE d.challenge_id = v_c.id;
    INSERT INTO public.admin_step_up (session_id, user_id, method, verified_at, expires_at)
    VALUES (v_c.session_id, v_c.user_id, COALESCE(v_method, 'whatsapp'), now(), now() + interval '12 hours')
    ON CONFLICT (session_id) DO UPDATE
      SET method = EXCLUDED.method, verified_at = now(), expires_at = EXCLUDED.expires_at
      WHERE public.admin_step_up.user_id = EXCLUDED.user_id;
  ELSE
    INSERT INTO public.admin_otp_phones (user_id, phone_e164, verified_at)
    VALUES (v_c.user_id, v_c.phone_e164, now())
    ON CONFLICT (user_id) DO UPDATE SET phone_e164 = EXCLUDED.phone_e164, verified_at = now();
  END IF;

  RETURN jsonb_build_object('ok', true, 'reason', null, 'attempts_left', 5 - v_c.attempts, 'purpose', v_c.purpose);
END;
$$;

-- ---------------------------------------------------------------------------
-- E) Delivery bookkeeping (WhatsApp status webhook, SMS fallback)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.otp_delivery_record(
  p_challenge_id uuid,
  p_channel      text,
  p_message_id   text,
  p_status       text,
  p_error        text DEFAULT NULL
) RETURNS uuid
LANGUAGE sql
SECURITY INVOKER
SET search_path = ''
AS $$
  INSERT INTO public.otp_deliveries (challenge_id, channel, provider_message_id, status, error)
  VALUES (p_challenge_id, p_channel, NULLIF(p_message_id, ''), p_status, left(p_error, 200))
  ON CONFLICT (provider_message_id) DO UPDATE SET updated_at = now()
  RETURNING id;
$$;

-- Forward-only status changes: sent -> delivered -> read; failed is terminal
-- unless a later "delivered"/"read" arrives (Meta can resend statuses).
CREATE OR REPLACE FUNCTION public.otp_delivery_status(
  p_message_id text,
  p_status     text
) RETURNS boolean
LANGUAGE sql
SECURITY INVOKER
SET search_path = ''
AS $$
  WITH upd AS (
    UPDATE public.otp_deliveries d
       SET status = p_status, updated_at = now()
     WHERE d.provider_message_id = p_message_id
       AND p_status IN ('sent', 'delivered', 'read', 'failed')
       AND (CASE p_status WHEN 'sent' THEN 1 WHEN 'failed' THEN 1 WHEN 'delivered' THEN 2 WHEN 'read' THEN 3 END)
         > (CASE d.status WHEN 'sent' THEN 0 WHEN 'failed' THEN 1 WHEN 'delivered' THEN 2 WHEN 'read' THEN 3 END)
    RETURNING 1)
  SELECT EXISTS (SELECT 1 FROM upd);
$$;

-- Should the SMS fallback go out? Only when the code it would send is still
-- the live one (same send number, not used, not locked, not expired) and
-- WhatsApp has not reported it delivered or read.
CREATE OR REPLACE FUNCTION public.otp_fallback_needed(p_challenge_id uuid, p_sends smallint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  SELECT EXISTS (
           SELECT 1 FROM public.otp_challenges c
            WHERE c.id = p_challenge_id AND c.sends = p_sends
              AND c.consumed_at IS NULL AND c.locked_at IS NULL AND c.expires_at > now())
     AND NOT EXISTS (
           SELECT 1 FROM public.otp_deliveries d
            WHERE d.challenge_id = p_challenge_id AND d.channel = 'whatsapp'
              AND d.status IN ('delivered', 'read')
              AND d.created_at >= (SELECT c.last_sent_at FROM public.otp_challenges c WHERE c.id = p_challenge_id));
$$;

CREATE OR REPLACE FUNCTION public.admin_remove_otp_phone(p_user_id uuid)
RETURNS void
LANGUAGE sql
SECURITY INVOKER
SET search_path = ''
AS $$
  DELETE FROM public.admin_otp_phones WHERE user_id = p_user_id;
  DELETE FROM public.admin_step_up WHERE user_id = p_user_id;
$$;

